import assert from 'node:assert/strict';
import { ADMIN_ID, loadTeachers, saveTeacher, setTeacherActive, teacherClassesKey } from '../js/teacher-repository.js';
import { listAccessProfiles, resolveAccessProfile, canManageTeachers, canOpenCalendar, profileDestination } from '../js/access-service.js';
import { currentDemoProfile, startDemoSession, endDemoSession } from '../js/demo-session.js';
import { createStore } from '../js/store.js';
import { loadStudentCatalog } from '../js/student-data.js';
const data=new Map(), session=new Map();
globalThis.localStorage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
globalThis.sessionStorage={getItem:k=>session.get(k)??null,setItem:(k,v)=>session.set(k,v),removeItem:k=>session.delete(k)};
const ana=saveTeacher({name:'Ana Solís',subjects:['Biología']});
const luis=saveTeacher({name:'Luis Mora',subjects:['Química']});
const profiles=listAccessProfiles(loadTeachers());
assert.equal(profiles.length,3);
assert.equal(profiles[0].role,'admin');
assert.equal(resolveAccessProfile('inexistente',loadTeachers()),null);
assert.equal(currentDemoProfile(),null);
assert.throws(()=>startDemoSession('inexistente'),/perfil activo/);
const admin=startDemoSession(ADMIN_ID);
assert.ok(canManageTeachers(admin));
assert.ok(canOpenCalendar(admin,ana.id,loadTeachers()));
assert.ok(canOpenCalendar(admin,ADMIN_ID,loadTeachers()));
assert.equal(profileDestination(admin),'panel.html');
const teacher=startDemoSession(ana.id);
assert.equal(teacher.role,'teacher');
assert.ok(!canManageTeachers(teacher));
assert.ok(canOpenCalendar(teacher,ana.id,loadTeachers()));
assert.ok(!canOpenCalendar(teacher,luis.id,loadTeachers()));
assert.ok(!canOpenCalendar(teacher,ADMIN_ID,loadTeachers()));
assert.equal(currentDemoProfile().id,ana.id);
assert.match(profileDestination(teacher),/horarios.html\?profesor=/);
setTeacherActive(ana.id,false);
assert.equal(currentDemoProfile(),null,'inactivo pierde acceso demo');
assert.throws(()=>startDemoSession(ana.id),/perfil activo/);
startDemoSession(ADMIN_ID);
const own=createStore(teacherClassesKey(ADMIN_ID));
own.add([{date:'2026-11-18',start:420,end:480,booked:false,group:false}]);
own.publish();
assert.ok(loadStudentCatalog().teachers.some(t=>t.id===ADMIN_ID));
assert.ok(loadStudentCatalog().classes.some(c=>c.teacherId===ADMIN_ID));
endDemoSession();assert.equal(currentDemoProfile(),null);
console.log('Acceso demo, roles, aislamiento de horarios y administrador docente: OK.');
