import assert from 'node:assert/strict';
import { ADMIN_ID, saveTeacher, teacherClassesKey, loadTeacherClasses } from '../js/teacher-repository.js';
import { createStore } from '../js/store.js';
import { reserveDemoClass, listReservations, listDemoNotifications } from '../js/reservation-service.js';
import { loadStudentCatalog, isClosed } from '../js/student-data.js';
const data = new Map();
globalThis.localStorage = {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
const prof = saveTeacher({name:'Profesora Prueba',subjects:['Biología']});
const store = createStore(teacherClassesKey(prof.id));
store.add([{date:'2026-12-01',start:900,end:960,group:true,capacity:2,online:true},{date:'2026-12-02',start:900,end:960,group:false,online:false}]);store.publish();
const [group, individual] = loadTeacherClasses(prof.id);
const base = {teacherId:prof.id,classId:group.id,name:'Estudiante Uno',email:'uno@example.com',subject:'Biología',grade:'11',mode:'online'};
assert.throws(()=>reserveDemoClass({...base,subject:'Física'}),/materia/);
assert.throws(()=>reserveDemoClass({...base,mode:'onsite'}),/modalidad/);
const r1 = reserveDemoClass(base);assert.match(r1.id,/^CM-/);
assert.equal(loadTeacherClasses(prof.id)[0].enrolled,1);
assert.equal(loadTeacherClasses(prof.id)[0].booked,true,'protección del constructor desde el primer cupo');
assert.equal(isClosed(loadStudentCatalog().classes.find(c=>c.teacherId===prof.id && c.id.endsWith(':'+group.id))),false,'queda un cupo disponible');
assert.throws(()=>reserveDemoClass(base),/ya tiene/);
reserveDemoClass({...base,name:'Estudiante Dos',email:'dos@example.com'});
assert.equal(loadTeacherClasses(prof.id)[0].booked,true);
assert.throws(()=>reserveDemoClass({...base,email:'tres@example.com'}),/cupos/);
const solo = {...base,classId:individual.id,mode:'onsite',email:'cuatro@example.com'};
reserveDemoClass(solo);
assert.equal(loadTeacherClasses(prof.id)[1].booked,true);
assert.equal(listReservations().length,3);
assert.equal(listDemoNotifications().length,3);
assert.equal(loadStudentCatalog().classes.filter(c=>c.teacherId===prof.id).every(isClosed),true);
assert.equal(loadStudentCatalog().teachers.some(t=>t.id===ADMIN_ID),true);
console.log('Reservaciones demo: validaciones, cupos, duplicados, persistencia y bandeja simulada OK.');
