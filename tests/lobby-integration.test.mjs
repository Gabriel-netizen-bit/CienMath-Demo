import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const read = file => readFileSync(new URL('../' + file, import.meta.url), 'utf8');
const home=read('index.html');
const schedule=read('horarios.html');
const teachers=read('js/profesores.js');
const students=read('estudiantes.html');
const teachersHtml=read('profesores.html');
for(const id of ['academia','programas','horarios','informacion']) assert.match(home,new RegExp(`id="${id}"`));
assert.match(home,/href="estudiantes.html"/);
assert.match(home,/data-open-access/);
assert.match(home,/href=\"acceso.html\"/);
assert.ok(existsSync(new URL('../acceso.html',import.meta.url)));
assert.ok(existsSync(new URL('../js/access-service.js',import.meta.url)));
assert.ok(existsSync(new URL('../js/demo-session.js',import.meta.url))); 
assert.match(home,/data-theme-toggle/);
assert.match(home,/Demo/);
assert.match(schedule,/id="work"/);
assert.match(schedule,/src="js\/main.js"/);
assert.match(teachers,/horarios\.html\?profesor=/);
assert.match(students,/href="index.html"/);
assert.match(teachersHtml,/href="panel.html"/);
assert.ok(existsSync(new URL('../assets/cienmath-ciencia-hero.webp',import.meta.url)));
console.log('Lobby integrado: rutas, secciones, arte y constructor original verificados.');
